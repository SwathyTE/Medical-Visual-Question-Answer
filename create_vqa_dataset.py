#!/usr/bin/env python3
"""
create_reasoning_vqa_dataset.py
================================
Generates a reasoning-augmented VQA dataset from raidium/RadImageNet-VQA
using google/medgemma-1.5-4b-it (instruct split).

Output schema (4 columns only):
  image     – copied verbatim from source (stored as PNG bytes in parquet)
  question  – copied verbatim from source
  answer    – copied verbatim from source
  reasoning – generated by MedGemma (the ONLY new column)

The number of QA pairs per image is preserved exactly as in the source.
Output filename: reasoning_vqa_<N>samples_<timestamp>.parquet

Usage
-----
    python create_reasoning_vqa_dataset.py [--samples N] [--hf-token TOKEN]
                                           [--output-dir DIR] [--device cuda|cpu]
                                           [--seed 42]

Arguments
---------
--samples    INT  Number of unique images to process (-1 = all).
                  Interactive prompt if omitted.
--hf-token   STR  HuggingFace token for gated model / dataset access.
                  Falls back to HF_TOKEN env var, then cached `huggingface-cli login`.
--output-dir STR  Directory to write the parquet file (default: current dir).
--device     STR  "cuda" | "cpu" | "auto"  (default: auto-detect).
--seed       INT  Random seed (default: 42).
"""

import argparse
import io
import json
import os
import random
import re
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

# ── third-party ──────────────────────────────────────────────────────────────
try:
    import torch
    from datasets import load_dataset
    from PIL import Image
    from transformers import (
        AutoProcessor,
        AutoModelForImageTextToText,
    )
    import pandas as pd
    from tqdm import tqdm
except ImportError as e:
    sys.exit(
        f"[ERROR] Missing dependency: {e}\n"
        "Install with:\n"
        "  pip install torch transformers datasets Pillow pandas pyarrow tqdm"
    )

# ── constants ─────────────────────────────────────────────────────────────────
MODEL_ID        = "google/medgemma-1.5-4b-it"
DATASET_ID      = "raidium/RadImageNet-VQA"
DATASET_CONFIG  = "instruct"   # config name  (alignment | instruct | benchmark)
SPLIT           = "train"      # split within that config

# MedGemma is told the correct answer and asked only to explain WHY it is
# correct — so reasoning is always grounded in the ground-truth label.
SYSTEM_PROMPT = (
    "You are an expert radiologist and medical imaging assistant. "
    "You will be given a medical image, a question about it, and the correct answer. "
    "Your sole task is to write a concise clinical reasoning (2-3 sentences maximum) "
    "that explains WHY that answer is correct, based on what you observe in the image "
    "and relevant medical knowledge.\n\n"
    "Rules:\n"
    "- Output ONLY the reasoning as plain prose.\n"
    "- Keep it concise: 2-3 sentences, no more.\n"
    "- Do NOT restate the question or the answer.\n"
    "- Do NOT use any tags, bullet headers, or preamble.\n"
    "- Be specific about the visual findings that support the answer."
)


# ── helpers ───────────────────────────────────────────────────────────────────

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create reasoning-augmented VQA dataset using MedGemma"
    )
    parser.add_argument(
        "--samples", type=int, default=None,
        help="Number of unique images to process (-1 = all). "
             "Interactive prompt if omitted.",
    )
    parser.add_argument(
        "--hf-token", type=str, default=None,
        help="HuggingFace access token",
    )
    parser.add_argument(
        "--output-dir", type=str, default=".",
        help="Output directory for the parquet file",
    )
    parser.add_argument(
        "--device", type=str, default="auto",
        choices=["auto", "cuda", "cpu"],
        help="Inference device",
    )
    parser.add_argument(
        "--seed", type=int, default=42,
        help="Random seed",
    )
    return parser.parse_args()


def resolve_token(cli_token: Optional[str]) -> Optional[str]:
    """CLI arg → HF_TOKEN env var → None (rely on cached login)."""
    if cli_token:
        return cli_token
    return os.environ.get("HF_TOKEN", None)


def resolve_device(pref: str) -> str:
    if pref == "auto":
        return "cuda" if torch.cuda.is_available() else "cpu"
    return pref


def prompt_for_samples() -> int:
    """Interactive prompt: ask the user how many images to include."""
    print("\n" + "=" * 60)
    print("  RadImageNet-VQA  →  Reasoning Dataset Generator")
    print("=" * 60)
    print("\nHow many unique images should be included in the new dataset?")
    print("  • Enter a positive integer  (e.g. 100)")
    print("  • Enter -1 to process ALL images in the instruct split")
    while True:
        raw = input("\nNumber of images [default: 50]: ").strip()
        if raw == "":
            return 50
        try:
            n = int(raw)
            if n == -1 or n > 0:
                return n
            print("  ⚠  Please enter a positive integer or -1.")
        except ValueError:
            print("  ⚠  Invalid input — please enter an integer.")


def debug_sample_schema(sample: Dict[str, Any]) -> None:
    """Print a one-time schema dump of the first dataset sample."""
    print("\n[DEBUG] First sample keys and value previews:", flush=True)
    for k, v in sample.items():
        if k == "image":
            print(f"  {k!r:30s} <image>")
        else:
            preview = repr(v)[:200]
            print(f"  {k!r:30s} {preview}")
    print(flush=True)


def _parse_turns(turns: List[Any]) -> List[Dict[str, str]]:
    """
    Walk a list of conversation turns and return (question, answer) pairs.

    Handles:
      A. [{"from":"human","value":Q}, {"from":"gpt","value":A}, ...]
      B. [{"role":"user","content":Q}, {"role":"assistant","content":A}, ...]
      C. [{"question":Q, "answer":A}, ...]   <- each dict is a complete QA pair
    """
    pairs: List[Dict[str, str]] = []
    i = 0
    while i < len(turns):
        turn = turns[i]
        if not isinstance(turn, dict):
            i += 1
            continue

        # Format C — single dict already contains both fields
        if "question" in turn and "answer" in turn:
            q = str(turn["question"]).strip()
            a = str(turn["answer"]).strip()
            if q:
                pairs.append({"question": q, "answer": a})
            i += 1
            continue

        # Formats A / B — alternating human/assistant turns
        role    = (turn.get("from") or turn.get("role") or "").lower()
        content = (turn.get("value") or turn.get("content") or "").strip()

        if role in ("human", "user") and i + 1 < len(turns):
            nxt      = turns[i + 1]
            nxt_role = (nxt.get("from") or nxt.get("role") or "").lower()
            # Accept any non-human role as the answer turn
            # (dataset uses 'template', others use 'gpt'/'assistant'/'model')
            if nxt_role not in ("human", "user", ""):
                a = (nxt.get("value") or nxt.get("content") or "").strip()
                # Strip <image> token and surrounding whitespace from question
                q_clean = re.sub(r"<image>\s*", "", content).strip()
                if q_clean:
                    pairs.append({"question": q_clean, "answer": a})
                i += 2
                continue

        i += 1
    return pairs


def parse_conversation(sample: Dict[str, Any]) -> List[Dict[str, str]]:
    """
    Extract (question, answer) pairs from a dataset sample.

    Priority order:
      1. Flat top-level  "question" / "answer"  fields  (one pair per row)
      2. Nested list in  "conversations" / "conversation" / "messages"
         -- supports human/gpt, user/assistant, and {question,answer} dict formats
      3. "question_answer" / "qa_pairs" list
    """

    # ── 1. Flat top-level fields ──────────────────────────────────────────────
    q_keys = ["question", "Question", "QUESTION", "query",    "Query"]
    a_keys = ["answer",   "Answer",   "ANSWER",   "response", "Response",
              "label",    "Label",    "correct_answer", "gt_answer"]

    q_val = next((str(sample[k]).strip() for k in q_keys
                  if k in sample and sample[k] not in (None, "")), None)
    a_val = next((str(sample[k]).strip() for k in a_keys
                  if k in sample and sample[k] not in (None, "")), None)

    if q_val and a_val:
        return [{"question": q_val, "answer": a_val}]

    # ── 2. Nested conversation list ───────────────────────────────────────────
    for field in ("conversations", "conversation", "messages", "dialog", "dialogue"):
        raw = sample.get(field)
        if not raw:
            continue
        if isinstance(raw, str):
            try:
                raw = json.loads(raw)
            except (json.JSONDecodeError, ValueError):
                continue
        if isinstance(raw, list) and raw:
            pairs = _parse_turns(raw)
            if pairs:
                return pairs

    # ── 3. "question_answer" / "qa_pairs" list ────────────────────────────────
    for field in ("question_answer", "qa_pairs", "qas"):
        qa_list = sample.get(field) or []
        if isinstance(qa_list, str):
            try:
                qa_list = json.loads(qa_list)
            except (json.JSONDecodeError, ValueError):
                qa_list = []
        if isinstance(qa_list, list) and qa_list:
            pairs = _parse_turns(qa_list)
            if pairs:
                return pairs

    return []


def load_pil_image(raw: Any) -> Optional[Image.Image]:
    """Convert whatever the dataset gives us into a PIL RGB image."""
    if isinstance(raw, Image.Image):
        return raw.convert("RGB")
    if isinstance(raw, dict) and "bytes" in raw:
        return Image.open(io.BytesIO(raw["bytes"])).convert("RGB")
    if isinstance(raw, bytes):
        return Image.open(io.BytesIO(raw)).convert("RGB")
    return None


def pil_to_bytes(img: Image.Image) -> bytes:
    """Encode a PIL image as PNG bytes (for parquet storage)."""
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def generate_reasoning(
    model,
    processor,
    image: Image.Image,
    question: str,
    answer: str,
    device: str,
    max_new_tokens: int = 150,
) -> str:
    """
    Ask MedGemma to produce reasoning that justifies `answer` for `question`.
    Returns plain-text reasoning (no tags).
    """
    user_text = (
        f"Question: {question}\n"
        f"Correct answer: {answer}\n\n"
        "In 2-3 sentences, explain concisely why this answer is correct "
        "based on what you observe in the medical image."
    )

    messages = [
        {
            "role": "system",
            "content": [{"type": "text", "text": SYSTEM_PROMPT}],
        },
        {
            "role": "user",
            "content": [
                {"type": "image", "image": image},
                {"type": "text",  "text": user_text},
            ],
        },
    ]

    inputs = processor.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=True,
        return_dict=True,
        return_tensors="pt",
    ).to(device)

    input_len = inputs["input_ids"].shape[-1]

    with torch.inference_mode():
        output_ids = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
        )

    new_tokens = output_ids[0][input_len:]
    return processor.decode(new_tokens, skip_special_tokens=True).strip()


# ── main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    args     = parse_args()
    random.seed(args.seed)

    hf_token = resolve_token(args.hf_token)
    device   = resolve_device(args.device)
    n_images = args.samples if args.samples is not None else prompt_for_samples()

    print(f"\n{'='*60}")
    print(f"  Dataset  : {DATASET_ID}  (config={DATASET_CONFIG}, split={SPLIT})")
    print(f"  Model    : {MODEL_ID}")
    print(f"  Images   : {'ALL' if n_images == -1 else n_images}")
    print(f"  Device   : {device}")
    print(f"  Output   : {args.output_dir}")
    print(f"  Schema   : image | question | answer | reasoning")
    print(f"{'='*60}\n")

    # ── 1. Load dataset ───────────────────────────────────────────────────────
    print("[1/4] Loading dataset...")
    ds_kwargs: Dict[str, Any] = {"split": SPLIT, "streaming": True}
    if hf_token:
        ds_kwargs["token"] = hf_token

    try:
        dataset = load_dataset(DATASET_ID, DATASET_CONFIG, **ds_kwargs)
    except Exception as exc:
        sys.exit(
            f"[ERROR] Could not load dataset '{DATASET_ID}'.\n"
            f"  Reason : {exc}\n\n"
            "Troubleshooting:\n"
            "  1. Run:  huggingface-cli login\n"
            "  2. Or:   --hf-token YOUR_TOKEN\n"
            "  3. Accept dataset licence at "
            f"huggingface.co/datasets/{DATASET_ID}\n"
            f"  Available configs: alignment | instruct | benchmark"
        )

    # ── 2. Collect unique-image samples ───────────────────────────────────────
    print("[2/4] Collecting samples from dataset stream...")
    image_samples: List[Dict[str, Any]] = []
    seen_ids: set = set()

    first_seen = False
    for sample in dataset:
        img_id = (
            sample.get("id")
            or sample.get("image_id")
            or sample.get("image_path")
            or str(len(image_samples))
        )
        if img_id in seen_ids:
            continue
        seen_ids.add(img_id)
        image_samples.append(sample)
        if not first_seen:
            debug_sample_schema(sample)   # one-time schema dump
            first_seen = True

        if n_images != -1 and len(image_samples) >= n_images:
            break

    actual_images = len(image_samples)
    total_qa      = sum(len(parse_conversation(s)) for s in image_samples)
    print(f"  → {actual_images} unique images, {total_qa} QA pairs total\n")

    if actual_images == 0:
        sys.exit(
            "[ERROR] No samples collected. "
            f"Check dataset access and that config='{DATASET_CONFIG}' split='{SPLIT}' exists."
        )

    # ── 3. Load MedGemma ──────────────────────────────────────────────────────
    print("[3/4] Loading MedGemma model...")
    load_kwargs: Dict[str, Any] = {}
    if hf_token:
        load_kwargs["token"] = hf_token

    load_kwargs["dtype"] = torch.bfloat16

    try:
        processor = AutoProcessor.from_pretrained(MODEL_ID, **load_kwargs)
        model     = AutoModelForImageTextToText.from_pretrained(
            MODEL_ID,
            device_map=device if device == "cuda" else None,
            **load_kwargs,
        )
        if device != "cuda":
            model = model.to(device)
        model.eval()
    except Exception as exc:
        sys.exit(
            f"[ERROR] Could not load model '{MODEL_ID}'.\n"
            f"  Reason : {exc}\n\n"
            "Troubleshooting:\n"
            "  1. Accept model licence at "
            "huggingface.co/google/medgemma-1.5-4b-it\n"
            "  2. Run:  huggingface-cli login  (or pass --hf-token)\n"
            "  3. Ensure enough memory (~8 GB VRAM for bfloat16)"
        )
    print("  → Model loaded\n")

    # ── 4. Generate reasoning & assemble rows ─────────────────────────────────
    print("[4/4] Generating reasoning for each QA pair...")
    rows:   List[Dict[str, Any]] = []
    errors: int = 0

    pbar = tqdm(image_samples, desc="Images", unit="img")
    for sample in pbar:
        image = load_pil_image(sample.get("image"))
        if image is None:
            pbar.write("  ⚠  Could not decode image — skipping sample.")
            errors += 1
            continue

        qa_pairs = parse_conversation(sample)
        if not qa_pairs:
            pbar.write("  ⚠  No QA pairs found — skipping sample.")
            errors += 1
            continue

        img_bytes = pil_to_bytes(image)   # encode once per image

        for qa in qa_pairs:
            question = qa["question"]
            answer   = qa["answer"]

            try:
                reasoning = generate_reasoning(
                    model, processor, image, question, answer, device
                )
            except Exception as err:
                pbar.write(f"  ⚠  Inference error: {err}")
                errors += 1
                reasoning = ""   # preserve the row with an empty reasoning field

            rows.append({
                "image"    : img_bytes,  # PNG bytes — identical to source image
                "question" : question,   # verbatim from source
                "answer"   : answer,     # verbatim from source
                "reasoning": reasoning,  # generated by MedGemma
            })

    print(f"\n  → {len(rows)} rows generated  ({errors} errors skipped)")

    if not rows:
        sys.exit("[ERROR] No rows generated. Cannot write parquet file.")

    # ── 5. Write parquet ──────────────────────────────────────────────────────
    timestamp    = datetime.now().strftime("%Y%m%d_%H%M%S")
    out_filename = f"reasoning_vqa_{actual_images}samples_{timestamp}.parquet"
    out_path     = Path(args.output_dir) / out_filename
    out_path.parent.mkdir(parents=True, exist_ok=True)

    df = pd.DataFrame(rows)
    df.to_parquet(out_path, index=False, engine="pyarrow")

    # ── 6. Summary ────────────────────────────────────────────────────────────
    size_mb = out_path.stat().st_size / (1024 * 1024)
    print(f"\n✅  Dataset saved  →  {out_path}")
    print(f"   Rows    : {len(df)}")
    print(f"   Columns : {list(df.columns)}")
    print(f"   Size    : {size_mb:.1f} MB")

    print("\nColumn dtypes:")
    for col, dtype in df.dtypes.items():
        print(f"  {col:<12} {dtype}")

    print("\nSample row preview (first row):")
    first = df.iloc[0]
    print(f"  question  : {first['question'][:120]}")
    print(f"  answer    : {first['answer'][:120]}")
    print(f"  reasoning : {first['reasoning'][:200]}...")
    print(f"  image     : <PNG bytes — {len(first['image'])} bytes>")


if __name__ == "__main__":
    main()
